import { afterAll, describe, expect, it } from 'vitest'
import { runCli } from '../helpers/cli.js'
import { createScenarioRepo, type ScenarioRepo } from '../helpers/repo.js'

const repos: ScenarioRepo[] = []
afterAll(() => {
  for (const r of repos) r.repo.cleanup()
})

function routes(scenario: string, ref: 'base' | 'head'): unknown {
  const s = createScenarioRepo(scenario)
  repos.push(s)
  const r = runCli(['--cwd', s.repo.dir, 'routes', '--ref', s[ref]])
  expect(r.stderr).toBe('')
  expect(r.code).toBe(0)
  return JSON.parse(r.stdout)
}

describe('routes command', () => {
  it('extracts the expected table from the base fixture', () => {
    expect(routes('11-routes-from-map', 'base')).toEqual({
      file: 'src/routes.tsx',
      routes: [
        { key: '/', path: '/', index: false, entry: 'src/layouts/AppLayout.tsx', modules: ['src/layouts/AppLayout.tsx'], layouts: [] },
        { key: '/ > (index)', path: '/', index: true, entry: 'src/pages/HomePage.tsx', modules: ['src/pages/HomePage.tsx'], layouts: ['src/layouts/AppLayout.tsx'] },
        { key: '/ > about', path: '/about', index: false, entry: 'src/pages/AboutPage.tsx', modules: ['src/pages/AboutPage.tsx'], layouts: ['src/layouts/AppLayout.tsx'] },
        { key: '/ > products', path: '/products', index: false, entry: 'src/pages/ProductsPage.tsx', modules: ['src/pages/ProductsPage.tsx'], layouts: ['src/layouts/AppLayout.tsx'] },
        { key: '/ > settings', path: '/settings', index: false, entry: 'src/pages/SettingsPage.tsx', modules: ['src/pages/SettingsPage.tsx'], layouts: ['src/layouts/AppLayout.tsx'] },
      ],
      dynamicRoutes: [],
      sources: ['src/routes.tsx'],
    })
  })

  it('11: routes generated by .map become a dynamic-route diagnostic', () => {
    const table = routes('11-routes-from-map', 'head') as { dynamicRoutes: unknown[]; routes: { key: string }[] }
    expect(table.dynamicRoutes).toEqual([{ file: 'src/routes.tsx', line: 18, detail: 'spread in route array "...simplePages.map(({ path, Page }) => ({ path, element: <Page /> }))"' }])
    // What could be read is still reported, so reviewers see the rest of the table.
    expect(table.routes.map((r) => r.key)).toEqual(['/', '/ > (index)', '/ > settings'])
  })

  it('reads the working tree when --ref is omitted', () => {
    const s = createScenarioRepo('11-routes-from-map')
    repos.push(s)
    s.repo.write('src/routes.tsx', "import { createBrowserRouter } from 'react-router-dom'\nimport HomePage from './pages/HomePage'\nexport const router = createBrowserRouter([{ path: '/', element: <HomePage /> }])\n")
    const r = runCli(['--cwd', s.repo.dir, 'routes'])
    expect((JSON.parse(r.stdout) as { routes: { key: string }[] }).routes.map((x) => x.key)).toEqual(['/'])
  })

  it('fails with exit code 2 and an actionable message when the routes file is missing', () => {
    const s = createScenarioRepo('11-routes-from-map')
    repos.push(s)
    s.repo.write('farol.config.json', '{"routes":{"file":"src/router.tsx"}}')
    const r = runCli(['--cwd', s.repo.dir, 'routes'])
    expect(r.code).toBe(2)
    expect(r.stderr).toContain('routes file not found at src/router.tsx; adjust routes.file in the configuration')
  })
})
