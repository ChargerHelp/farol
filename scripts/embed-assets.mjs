// Copies the logo files of assets/ into src/report/html-assets.ts, so the single-file HTML report can embed them.
// Run by `npm run build` (and `npm run assets`); a test fails when the generated module and the files differ.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const files = readdirSync(join(root, 'assets')).filter((f) => f.endsWith('.svg')).sort()
const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(root, 'assets', f), 'utf8'))},`)
const out = `// Generated by scripts/embed-assets.mjs from assets/*.svg: do not edit (npm run assets).\n/** The logo files of assets/, by file name. */\nexport const ASSETS: Readonly<Record<string, string>> = {\n${entries.join('\n')}\n}\n`
writeFileSync(join(root, 'src/report/html-assets.ts'), out)
console.log(`embedded ${files.length} asset(s)`)
