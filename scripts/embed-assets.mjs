// Copies assets/*.svg (the logo) and assets/report/* (the HTML report's stylesheet and browser scripts) into
// src/report/html-assets.ts, so the single-file HTML report can embed them.
// Run by `npm run build` (and `npm run assets`); a test fails when the generated module and the files differ.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const logos = readdirSync(join(root, 'assets')).filter((f) => f.endsWith('.svg')).sort()
const report = readdirSync(join(root, 'assets/report')).filter((f) => f.endsWith('.js') || f.endsWith('.css')).sort().map((f) => `report/${f}`)
const files = [...logos, ...report]
const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(root, 'assets', f), 'utf8'))},`)
const out = `// Generated by scripts/embed-assets.mjs from assets/: do not edit (npm run assets).\n/** The files of assets/ (logo, report stylesheet and scripts), by path. */\nexport const ASSETS: Readonly<Record<string, string>> = {\n${entries.join('\n')}\n}\n`
writeFileSync(join(root, 'src/report/html-assets.ts'), out)
console.log(`embedded ${files.length} asset(s)`)
